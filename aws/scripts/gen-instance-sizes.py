#!/usr/bin/env python3
"""Print saturn-aws-instance-sizes.tf from saturn-aws's instance_types.py.

    git -C <saturn-aws> show <commit>:saturn_aws/instance_types.py > /tmp/it.py
    python3 -I scripts/gen-instance-sizes.py /tmp/it.py <commit> > saturn-aws-instance-sizes.tf

The file is parsed, not imported, so saturn-aws's dependencies are not needed.
"""
import ast
import json
import sys

# AWSASGConfig._get_accelerator in saturn_aws/instance_types.py.
ACCELERATORS = (
    ("g4dn", "nvidia-tesla-t4"),
    ("p3", "nvidia-tesla-v100"),
    ("g5", "nvidia-ampere-a10g"),
    ("p4", "nvidia-ampere-a100"),
)


def accelerator(instance_type, gpu):
    if not gpu:
        return ""
    for prefix, name in ACCELERATORS:
        if instance_type.startswith(prefix):
            return name
    raise ValueError(f"unknown GPU instance type {instance_type}")


def aws_sizes(path):
    for node in ast.parse(open(path).read()).body:
        if isinstance(node, ast.Assign) and getattr(node.targets[0], "id", "") == "aws_instance_config":
            for key, value in zip(node.value.keys, node.value.values):
                if key.value == "sizes":
                    sizes = []
                    for call in value.elts:
                        if call.keywords and call.keywords[0].arg is None:
                            sizes.append(ast.literal_eval(call.keywords[0].value))
                        else:
                            sizes.append({kw.arg: ast.literal_eval(kw.value) for kw in call.keywords})
                    return sizes
    raise ValueError("aws_instance_config sizes not found")


def main(path, commit):
    lines = [
        "# saturn-aws's AWS instance sizes: aws_instance_config[\"sizes\"] in",
        f"# saturn_aws/instance_types.py at release-2026.02.01 (commit {commit}), in the",
        "# same order. accelerator is what AWSASGConfig derives from the instance type.",
        "# Generated by scripts/gen-instance-sizes.py; do not edit by hand.",
        "locals {",
        "  saturn_aws_instance_sizes = [",
    ]
    for s in aws_sizes(path):
        gpu = s.get("gpu", 0)
        fields = [
            ("name", json.dumps(s["name"])),
            ("display_name", json.dumps(s["display_name"])),
            ("instance_type", json.dumps(s["instance_type"])),
            ("spot_instance_types", json.dumps(s["spot_instance_types"]).replace('","', '", "')),
            ("cores", str(s["cores"])),
            ("memory", json.dumps(s["memory"])),
            ("gpu", str(gpu)),
            ("accelerator", json.dumps(accelerator(s["instance_type"], gpu))),
        ]
        lines.append("    {")
        lines += [f"      {k:<19} = {v}" for k, v in fields]
        lines.append("    },")
    lines += ["  ]", "}"]
    print("\n".join(lines))


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
